/**
 * Generates src/components/tech/tech-icons.generated.ts from the `simple-icons` package.
 *
 * Why: `simple-icons` ships every icon (~5 MB of JS) from a single entry point and Metro does not
 * tree-shake by default, so importing `{ siReact }` would bundle all of them. This script copies only
 * the curated icons (path + brand hex + title) into a tiny typed module.
 *
 * Run from apps/mobile:  node scripts/generate-tech-icons.cjs
 */
const fs = require('node:fs');
const path = require('node:path');
const icons = require('simple-icons');

/** key -> [simple-icons export, regex source matched against the plan's free-text technology] */
const CURATED = {
  react: ['siReact', '\\breact(\\s*native)?\\b|\\bjsx\\b'],
  nextjs: ['siNextdotjs', '\\bnext(\\.?js)?\\b'],
  nodejs: ['siNodedotjs', '\\bnode(\\.?js)?\\b'],
  express: ['siExpress', '\\bexpress(\\.?js)?\\b'],
  nestjs: ['siNestjs', '\\bnest(\\.?js)?\\b'],
  typescript: ['siTypescript', '\\btypescript\\b|\\bts\\b'],
  javascript: ['siJavascript', '\\bjavascript\\b|\\bjs\\b|\\becmascript\\b'],
  python: ['siPython', '\\bpython\\b|\\bpy\\b'],
  django: ['siDjango', '\\bdjango\\b'],
  flask: ['siFlask', '\\bflask\\b'],
  fastapi: ['siFastapi', '\\bfast\\s?api\\b'],
  java: ['siOpenjdk', '\\bjava\\b|\\bjvm\\b|\\bjdk\\b'],
  spring: ['siSpringboot', '\\bspring(\\s*boot)?\\b'],
  kotlin: ['siKotlin', '\\bkotlin\\b'],
  go: ['siGo', '\\bgo(lang)?\\b'],
  rust: ['siRust', '\\brust\\b'],
  cplusplus: ['siCplusplus', 'c\\+\\+|\\bcpp\\b'],
  c: ['siC', '^c$|\\bc language\\b|\\bansi c\\b'],
  dotnet: ['siDotnet', '\\.net\\b|\\bdotnet\\b|\\bc#|\\bcsharp\\b|\\basp\\.net\\b'],
  ruby: ['siRubyonrails', '\\brails\\b|\\bruby\\b'],
  php: ['siPhp', '\\bphp\\b'],
  laravel: ['siLaravel', '\\blaravel\\b'],
  swift: ['siSwift', '\\bswift(ui)?\\b'],
  ios: ['siApple', '\\bios\\b|\\bobjective-?c\\b'],
  android: ['siAndroid', '\\bandroid\\b'],
  flutter: ['siFlutter', '\\bflutter\\b'],
  dart: ['siDart', '\\bdart\\b'],
  expo: ['siExpo', '\\bexpo\\b'],
  angular: ['siAngular', '\\bangular\\b'],
  vue: ['siVuedotjs', '\\bvue(\\.?js)?\\b|\\bnuxt\\b'],
  svelte: ['siSvelte', '\\bsvelte(kit)?\\b'],
  redux: ['siRedux', '\\bredux\\b'],
  html: ['siHtml5', '\\bhtml5?\\b'],
  css: ['siCss', '\\bcss3?\\b'],
  tailwind: ['siTailwindcss', '\\btailwind\\b'],
  graphql: ['siGraphql', '\\bgraphql\\b'],
  postgresql: ['siPostgresql', '\\bpostgres(ql)?\\b|\\bsql\\b'],
  mysql: ['siMysql', '\\bmysql\\b'],
  mongodb: ['siMongodb', '\\bmongo(db)?\\b'],
  redis: ['siRedis', '\\bredis\\b'],
  kafka: ['siApachekafka', '\\bkafka\\b'],
  elasticsearch: ['siElasticsearch', '\\belastic(search)?\\b'],
  docker: ['siDocker', '\\bdocker\\b|\\bcontainers?\\b'],
  kubernetes: ['siKubernetes', '\\bkubernetes\\b|\\bk8s\\b'],
  terraform: ['siTerraform', '\\bterraform\\b'],
  googlecloud: ['siGooglecloud', '\\bgcp\\b|\\bgoogle cloud\\b'],
  linux: ['siLinux', '\\blinux\\b|\\bunix\\b|\\bbash\\b'],
  git: ['siGit', '\\bgit\\b'],
  pytorch: ['siPytorch', '\\bpytorch\\b|\\bdeep learning\\b'],
  tensorflow: ['siTensorflow', '\\btensorflow\\b|\\bkeras\\b'],
  pandas: ['siPandas', '\\bpandas\\b|\\bdata (science|analysis)\\b'],
  spark: ['siApachespark', '\\bspark\\b'],
  firebase: ['siFirebase', '\\bfirebase\\b'],
  jest: ['siJest', '\\bjest\\b|\\btesting\\b'],
  leetcode: ['siLeetcode', '\\bdsa\\b|\\balgorithms?\\b|\\bdata structures?\\b|\\bleetcode\\b|\\bcoding interview\\b'],
};

const lines = [];
lines.push('// AUTO-GENERATED by scripts/generate-tech-icons.cjs from the `simple-icons` package (CC0-1.0).');
lines.push('// Brand logos are trademarks of their respective owners. Do not edit by hand.');
lines.push('');
lines.push('export interface TechIcon {');
lines.push('  key: string;');
lines.push('  title: string;');
lines.push('  /** Brand colour without the leading # */');
lines.push('  hex: string;');
lines.push('  /** SVG path on a 24x24 viewBox */');
lines.push('  path: string;');
lines.push('  /** Case-insensitive pattern matched against free-text technology names */');
lines.push('  pattern: RegExp;');
lines.push('}');
lines.push('');
lines.push('export const TECH_ICONS: readonly TechIcon[] = [');
for (const [key, [exportName, pattern]] of Object.entries(CURATED)) {
  const icon = icons[exportName];
  if (!icon) throw new Error(`simple-icons has no export named ${exportName}`);
  lines.push(
    `  { key: ${JSON.stringify(key)}, title: ${JSON.stringify(icon.title)}, hex: ${JSON.stringify(icon.hex)}, path: ${JSON.stringify(icon.path)}, pattern: /${pattern}/i },`,
  );
}
lines.push('];');
lines.push('');

const out = path.join(__dirname, '..', 'src', 'components', 'tech', 'tech-icons.generated.ts');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${Object.keys(CURATED).length} icons to ${path.relative(process.cwd(), out)}`);
